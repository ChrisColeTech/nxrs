//! nxos-dev: builds a game executable from the translator's output with the os layer.
//!
//!     nxos-dev build --gen <generated C dir> --out <game.exe> [--obj <dir>] [--jobs 4]
//!
//! Compiles every chunk of the generated C (`<gen>/<module>/*.c`) with clang and the os layer's `cpu.h` overlay
//! (`src/os/include`: SVCs to `nxos_svc`, the counter to `nxos_ticks` at the title's rate), reusing objects newer
//! than their source, writes `modules.c` (the module table and `main` calling `nxos_main`), and links everything
//! with `nxos.lib` (the os layer with the runtime), which sits beside this executable.

use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::atomic::{AtomicUsize, Ordering};
use std::sync::Mutex;

type R<T> = Result<T, String>;

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn llvm(tool: &str) -> PathBuf {
    if let Ok(d) = std::env::var("NXRT_LLVM") {
        return Path::new(&d).join(format!("{tool}.exe"));
    }
    let p = Path::new(r"C:\Program Files\LLVM\bin").join(format!("{tool}.exe"));
    if p.is_file() {
        p
    } else {
        tool.into()
    }
}

fn run(cmd: &mut Command) -> R<String> {
    let out = cmd.output().map_err(|e| format!("{:?}: {e}", cmd.get_program()))?;
    if !out.status.success() {
        return Err(format!(
            "{:?} {:?} failed:\n{}{}",
            cmd.get_program(),
            cmd.get_args().collect::<Vec<_>>(),
            String::from_utf8_lossy(&out.stdout),
            String::from_utf8_lossy(&out.stderr)
        ));
    }
    Ok(String::from_utf8_lossy(&out.stdout).into_owned())
}

/// Runs the commands on `n` threads; a failed one is retried once (this machine's compilers fail at random under
/// load), then the first error wins.
fn parallel(cmds: Vec<Command>, n: usize) -> R<()> {
    let next = AtomicUsize::new(0);
    let total = cmds.len();
    let cmds: Vec<Mutex<Command>> = cmds.into_iter().map(Mutex::new).collect();
    let err: Mutex<Option<String>> = Mutex::new(None);
    let done = AtomicUsize::new(0);
    std::thread::scope(|s| {
        for _ in 0..n.max(1) {
            s.spawn(|| loop {
                let i = next.fetch_add(1, Ordering::Relaxed);
                let Some(c) = cmds.get(i) else { break };
                if err.lock().unwrap().is_some() {
                    break;
                }
                let mut c = c.lock().unwrap();
                let r = run(&mut c).or_else(|_| run(&mut c));
                if let Err(e) = r {
                    *err.lock().unwrap() = Some(e);
                    break;
                }
                let d = done.fetch_add(1, Ordering::Relaxed) + 1;
                if d.is_multiple_of(20) || d == total {
                    eprintln!("nxos-dev: compiled {d}/{total}");
                }
            });
        }
    });
    match err.into_inner().unwrap() {
        Some(e) => Err(e),
        None => Ok(()),
    }
}

const GEN_FLAGS: &[&str] = &[
    "-O1",
    "-fno-strict-aliasing",
    "-Wno-return-type",
    "-Wno-unused-label",
    "-march=x86-64-v3",
    "-fno-vectorize",
    "-fno-slp-vectorize",
    "-fomit-frame-pointer",
    "-g0",
    "-fms-runtime-lib=dll",
    "-w",
];

fn layout_modules(gen: &Path) -> R<Vec<(String, String, String)>> {
    let layout = std::fs::read_to_string(gen.join("layout.json")).map_err(|e| format!("layout.json: {e}"))?;
    let field = |chunk: &str, k: &str| -> Option<String> {
        let i = chunk.find(&format!("\"{k}\""))?;
        let rest = &chunk[i + k.len() + 2..];
        let a = rest.find('"')? + 1;
        let b = rest[a..].find('"')? + a;
        Some(rest[a..b].to_string())
    };
    let mut mods = vec![];
    for chunk in layout.split('{').skip(1) {
        let (Some(n), Some(b), Some(s)) = (field(chunk, "name"), field(chunk, "base"), field(chunk, "size")) else {
            return Err("layout.json: unexpected shape".into());
        };
        if gen.join(&n).join(format!("{n}_table.c")).is_file() {
            mods.push((n, b, s));
        }
    }
    Ok(mods)
}

fn modules_c(mods: &[(String, String, String)]) -> String {
    let mut s = String::from(
        "// Generated by nxos-dev: the translated modules for nxos_main.\n#include \"nxrt.h\"\n\n\
         volatile int g_fnprof __attribute__((visibility(\"hidden\")));\n\
         uint8_t rt_patch_on[256] __attribute__((visibility(\"hidden\")));\n\
         int nxos_main(int argc, char **argv, const RtModule *mods, int count);\n\n",
    );
    for (n, _, _) in mods {
        s.push_str(&format!("extern const uint64_t {n}_fn_addrs[];\nextern const GuestFn {n}_fn_ptrs[];\nextern const uint64_t {n}_fn_count;\n"));
    }
    s.push_str("\nint main(int argc, char **argv) {\n    RtModule mods[] = {\n");
    for (n, b, z) in mods {
        s.push_str(&format!("        {{\"{n}\", {b}ull, {z}ull, {n}_fn_addrs, {n}_fn_ptrs, 0}},\n"));
    }
    s.push_str("    };\n");
    for (i, (n, _, _)) in mods.iter().enumerate() {
        s.push_str(&format!("    mods[{i}].count = {n}_fn_count;\n"));
    }
    s.push_str(&format!("    return nxos_main(argc, argv, mods, {});\n}}\n", mods.len()));
    s
}

fn newer(a: &Path, than: &Path) -> bool {
    let m = |p: &Path| std::fs::metadata(p).and_then(|m| m.modified()).ok();
    matches!((m(a), m(than)), (Some(x), Some(y)) if x >= y)
}

fn build(gen: &Path, obj: &Path, out: &Path, jobs: usize) -> R<()> {
    std::fs::create_dir_all(obj).map_err(|e| e.to_string())?;
    let mods = layout_modules(gen)?;
    let mut srcs = vec![];
    for (n, _, _) in &mods {
        for f in std::fs::read_dir(gen.join(n)).map_err(|e| e.to_string())?.filter_map(|e| e.ok()) {
            if f.path().extension().is_some_and(|x| x == "c") {
                srcs.push(f.path());
            }
        }
    }
    srcs.sort();
    let mc = obj.join("modules.c");
    std::fs::write(&mc, modules_c(&mods)).map_err(|e| e.to_string())?;
    let overlay = root().join("include");
    let incs = [overlay.clone(), gen.join("include"), root().join("../translator/runtime"), root().join("../runtime/include")];
    let mut cmds = vec![];
    let mut objs = vec![];
    for src in srcs.iter().chain(std::iter::once(&mc)) {
        let o = obj.join(format!("{}.o", src.file_stem().unwrap().to_string_lossy()));
        let fresh = newer(&o, src) && newer(&o, &overlay.join("cpu.h")) && src != &mc;
        if !fresh {
            let mut c = Command::new(llvm("clang"));
            c.args(GEN_FLAGS);
            for inc in &incs {
                c.arg(format!("-I{}", inc.display()));
            }
            c.arg("-c").arg(src).arg("-o").arg(&o);
            cmds.push(c);
        }
        objs.push(o);
    }
    eprintln!("nxos-dev: {} modules, {} sources, {} to compile", mods.len(), objs.len(), cmds.len());
    parallel(cmds, jobs)?;
    let exe = std::env::current_exe().unwrap();
    let lib = exe.parent().unwrap().join("nxos.lib");
    if !lib.is_file() {
        return Err(format!("{} missing: cargo build -p os", lib.display()));
    }
    let mut c = Command::new(llvm("clang"));
    c.arg("-fuse-ld=lld")
        .arg("-fms-runtime-lib=dll")
        .args(&objs)
        .arg(&lib)
        .args(["-lkernel32", "-lntdll", "-luserenv", "-lws2_32", "-ldbghelp", "-ladvapi32", "-lbcrypt", "-lsynchronization", "-lole32", "-loleaut32"])
        .arg("-Wl,/STACK:0x1000000")
        .arg("-o")
        .arg(out);
    run(&mut c)?;
    eprintln!("nxos-dev: linked {}", out.display());
    Ok(())
}

fn arg(args: &[String], name: &str) -> Option<String> {
    args.iter().position(|a| a == name).and_then(|i| args.get(i + 1).cloned())
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let r = match args.first().map(String::as_str) {
        Some("build") => {
            let (Some(g), Some(o)) = (arg(&args, "--gen"), arg(&args, "--out")) else {
                eprintln!("usage: nxos-dev build --gen <dir> --out <exe> [--obj <dir>] [--jobs 4]");
                std::process::exit(2);
            };
            let gen = PathBuf::from(&g);
            let obj = arg(&args, "--obj").map(PathBuf::from).unwrap_or_else(|| gen.parent().unwrap_or(Path::new(".")).join("obj"));
            let jobs = arg(&args, "--jobs").and_then(|j| j.parse().ok()).unwrap_or(4);
            build(&gen, &obj, Path::new(&o), jobs)
        }
        _ => {
            eprintln!("usage: nxos-dev build --gen <dir> --out <exe> [--obj <dir>] [--jobs 4]");
            std::process::exit(2);
        }
    };
    if let Err(e) = r {
        eprintln!("nxos-dev: {e}");
        std::process::exit(1);
    }
}
